import type { PromiseThemeKey } from '../../domain/value-objects/PromiseTheme';

/**
 * Tonos disponibles para clasificar el mensaje central de cada promesa.
 * Se usan para poder filtrar/agrupar tarjetas por sentimiento dominante.
 */
export type PromiseTone =
  | 'esperanza'
  | 'paz'
  | 'fortaleza'
  | 'provision'
  | 'amor'
  | 'proposito'
  | 'gozo'
  | 'fidelidad';

/**
 * Semilla de datos de una tarjeta de promesa bíblica.
 *
 * Este tipo describe el contenido puro de una tarjeta: la referencia y el
 * texto del versículo (Reina-Valera 1960), la variante visual (`themeKey`)
 * que se le asignará y metadatos de presentación (`highlight`, `tone`).
 * No contiene ninguna lógica ni JSX: es la capa de datos de infraestructura.
 */
export interface PromiseCardSeed {
  /** Slug estable e inmutable, ej. 'santiago-1-17'. Se usa como clave de barajado. */
  readonly id: string;
  /** Referencia bíblica legible, ej. 'Santiago 1:17'. */
  readonly reference: string;
  /** Texto completo del versículo en español (Reina-Valera 1960). */
  readonly text: string;
  /** Versión bíblica usada. Por ahora solo soportamos RVR1960. */
  readonly version: 'RVR1960';
  /** Variante visual asignada a la tarjeta (ver `PromiseTheme.ts`). */
  readonly themeKey: PromiseThemeKey;
  /** 1 a 3 palabras/frases del texto a resaltar visualmente (deben existir literalmente en `text`). */
  readonly highlight: readonly string[];
  /** Tono/sentimiento dominante del versículo. */
  readonly tone: PromiseTone;
}

